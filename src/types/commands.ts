export interface ComposedPart {
	keys: string;
	meaning: string;
}

export interface CommandEntry {
	id: string;
	title: string;
	description: string;
	/** Key sequence in Vim notation, e.g. `ciw`, `<C-w>v`, `<leader>ff`. */
	keys: string;
	/** Leader-expanded display form, e.g. `Space f f`. Only set when it differs from `keys`. */
	keysDisplay?: string;
	/** Keys with <leader> expanded to the real key, e.g. `<Space>ff`. Runtime mappings only. */
	keysExpanded?: string;
	modes: Mode[];
	category: Category;
	source: Source;
	/** Specific attribution such as "Telescope" or "Snacks", only when provable. */
	sourceName?: string;
	keywords: string[];
	aliases: string[];
	examples?: string[];
	notes?: string;
	status: EntryStatus;
	/** Why the entry may not be available, e.g. "Requires Neovim 0.11+". */
	availabilityReason?: string;
	/** Runtime context: buffer, filetype, plugin, file:line. */
	context?: string;
	/** Mapping right-hand side (string rhs or "<Lua callback>"). */
	rhs?: string;
	/** Which editor the runtime mapping was discovered in. */
	editor?: "vim" | "neovim";
	/** Set for commands generated by the operator/text-object composer. */
	composed?: ComposedPart[];
}

export function isAvailable(entry: CommandEntry): boolean {
	return entry.status === "active" || entry.status === "buffer-local";
}
