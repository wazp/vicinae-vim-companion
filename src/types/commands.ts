/** Editor modes, using the single-letter codes from `:help map-modes`. */
export type Mode = "n" | "v" | "x" | "s" | "o" | "i" | "c" | "t" | "l";

export const MODE_LABELS: Record<Mode, string> = {
	n: "Normal",
	v: "Visual",
	x: "Visual",
	s: "Select",
	o: "Operator-pending",
	i: "Insert",
	c: "Command-line",
	t: "Terminal",
	l: "Lang-arg",
};

/** Where an entry came from. */
export type Source = "vim" | "neovim" | "lazyvim" | "plugin" | "custom";

export const SOURCE_LABELS: Record<Source, string> = {
	vim: "Vim",
	neovim: "Neovim",
	lazyvim: "LazyVim",
	plugin: "Plugin",
	custom: "User config",
};

/**
 * How much evidence there is that the entry works in the user's editor.
 *
 * - reference: documented built-in behavior (curated, not introspected)
 * - active: global mapping observed in a running editor
 * - buffer-local: observed, but only in the buffer that was inspected
 * - declared: declared by a plugin spec (lazy.nvim `keys`), plugin not loaded yet
 * - conditional: only exists after a filetype, LSP attach or similar event
 * - overridden: a declared/reference mapping shadowed by an active one
 */
export type EntryStatus =
	| "reference"
	| "active"
	| "buffer-local"
	| "declared"
	| "conditional"
	| "overridden";

export const STATUS_LABELS: Record<EntryStatus, string> = {
	reference: "Built-in reference",
	active: "Active global mapping",
	"buffer-local": "Buffer-local mapping",
	declared: "Plugin-declared mapping",
	conditional: "Conditional mapping",
	overridden: "Overridden",
};

